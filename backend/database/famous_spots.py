def get_famous_spots_for_destination(destination: str) -> list[dict[str, Any]]:
    """Return famous curated spots for a destination."""
    if not destination:
        return []

    dest_cleaned = destination.split(",")[0].strip().lower()
    dest_norm = dest_cleaned.replace("-", " ")
    if dest_norm in {"nyc", "ny", "manhattan", "brooklyn"}:
        dest_norm = "new york"
    if dest_norm in {"switzerland", "alps", "interlaken", "zermatt", "lauterbrunnen", "grindelwald"}:
        dest_norm = "swiss alps"

    for key, spots in FAMOUS_DESTINATION_SPOTS.items():
        k_norm = key.replace("-", " ")
        if k_norm == dest_norm or k_norm in dest_norm or dest_norm in k_norm:
            return spots

    return []
